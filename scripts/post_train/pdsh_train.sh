#!/bin/bash
set -x

if [ $# -ne 1 ]; then
  echo "Usage: $0 <script>"
  exit 1
fi

script=$1
export node_ip=$(echo ${NODE_IP_LIST} | sed 's/:8//g')

CURRENT_DIR=$(pwd)
worker_num=$(( $NODE_NUM / 8 ))

REMOTE_ENV=""
for var_name in \
  START_EXPR_TIME CURRENT_TIME EXPERIMENT_TAG \
  LEARNING_RATE BATCH_SIZE NUM_GENERATIONS MAX_STEPS SP_SIZE SAVE_INTERVAL \
  VALIDATE_AT_STEP0 ENABLE_EMOTION_SCORERS \
  CLIP_AUTT_WEIGHT R1OMNI_WEIGHT R1OMNI_VAD_MODE \
  ENABLE_CHROMATIC ENABLE_KINETIC \
  ENABLE_MOTION_NATURALNESS MOTION_NATURALNESS_WEIGHT MOTION_NATURALNESS_TARGET_AROUSAL \
  ADAPTIVE_REFLECT_CONTROL REFLECT_WARMUP_START_STEP REFLECT_FULL_ON_STEP \
  REFLECT_CONFLICT_SUPPRESSION REFLECT_SUBTLE_PROMPT_GATING \
  TRAIN_EXTRA_ARGS PUBLIC_VLM_ROOT EMO_REWARD_VLM_PRESET VIDEOALIGN_VLM_PRESET \
  EMO_REWARD_PLAN_ENABLED EMO_REWARD_PLAN_BACKEND EMO_REWARD_PLAN_GEMINI_MODEL \
  EMO_REWARD_PLAN_API_HOST EMO_REWARD_PLAN_API_APP_IDS EMO_REWARD_PLAN_API_APP_WEIGHTS \
  EMO_REWARD_PLAN_MAX_RETRIES EMO_REWARD_PLAN_NET_RETRIES EMO_REWARD_PLAN_MAX_OUTPUT_TOKENS \
  EMO_REWARD_PLAN_THINKING_BUDGET EMO_REWARD_PLAN_TIMEOUT_SEC \
  REWARD_GATE_POLICY REWARD_GATE_SINGLE_TOOL REWARD_GATE_JIT_TABLE \
  SDE_TYPE REWARD_MODEL \
  EMO_REWARD_COMBINE_VIDEOALIGN VIDEOALIGN_FUSION_ALPHA VIDEOALIGN_FUSION_BETA \
  AUTO_RESUME_TRAIN HOST_PATH LOCAL_IP CHIEF_IP HOST_NUM HOST_GPU_NUM NODE_IP_LIST NODE_NUM GPU_NAME \
  config_file config_index resume
  do
  eval "var_value=\${$var_name}"
  if [ -n "$var_value" ]; then
    REMOTE_ENV="$REMOTE_ENV $var_name=$(printf '%q' "$var_value")"
  fi
done

pdsh -w $node_ip -f $worker_num "cd ${CURRENT_DIR}; env ${REMOTE_ENV} bash $script"
